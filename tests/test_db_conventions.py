from datetime import date, datetime
from decimal import Decimal

from sqlalchemy.dialects import postgresql
from sqlalchemy.orm import Mapped, mapped_column
from sqlalchemy.schema import CreateTable

from pickled.db import Base, IdPk


class Example(Base):
    __tablename__ = "example"

    id: Mapped[IdPk]
    price_cents: Mapped[int]
    quantity: Mapped[Decimal]
    observed_at: Mapped[datetime]
    week_start: Mapped[date]
    note: Mapped[str | None] = mapped_column()


def ddl() -> str:
    return str(CreateTable(Example.__table__).compile(dialect=postgresql.dialect()))


def test_id_is_a_bigint_identity_key():
    assert "id BIGINT GENERATED BY DEFAULT AS IDENTITY" in ddl()
    assert "PRIMARY KEY (id)" in ddl()


def test_integers_are_bigint_so_cents_never_overflow():
    assert "price_cents BIGINT NOT NULL" in ddl()


def test_decimals_are_numeric():
    assert "quantity NUMERIC NOT NULL" in ddl()


def test_datetimes_are_timestamptz_and_dates_are_date():
    assert "observed_at TIMESTAMP WITH TIME ZONE NOT NULL" in ddl()
    assert "week_start DATE NOT NULL" in ddl()
